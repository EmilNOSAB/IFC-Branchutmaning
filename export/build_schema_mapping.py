"""Builds export/SchemaMapping.json for MicroStation's iTwin IFC exporter.

Why a builder?
--------------
The exporter reads a "Schema Mapping File" (MicroStation 2025 help: the file is
allocated based on the selected IFC version, other files can be browsed).
Bentley publishes the default mapping as an attachment on Bentley
Communities; the attachment requires a login and could not be retrieved
while developing this repository.  The parts of the format that ARE
documented publicly (Bentley Communities, "Default Schema mapping for Export
to IFC", versions 2-7) are:

  "GlobalVariables": {"ProcessEmptyProperties": "false", "JoinAssemblies": "false",
                      "ConstructionElements": "false", "ProcessGroupingElements": "false"}
  "ProjectConfigurations": {"ProjectName": ..., "SiteName": ..., "Authorization": ...,
                            "Author": {...}, "Organization": {...}}
  class entries in the "Mapping for Standard IFC classes" list, e.g.
      { "Class": [ "IFCDynamic", "IfcElementAssembly", "IfcElementAssembly" ] }
  comments are written as /* ... */

So the builder never invents structure:

* With ``--template`` (the default mapping delivered with the installed
  exporter, found and copied to output/env/ by microstation/inspect_environment.py)
  it keeps the template unchanged and only
    - sets the documented GlobalVariables,
    - fills ProjectConfigurations from config/model_config.yaml,
    - appends ``{"Class": ["IFCDynamic", <IfcClass>, <IfcClass>]}`` entries for the
      IFC 4.3 classes this project needs, in the list that already contains
      IFCDynamic class entries, copying the shape of an existing entry.  If no
      such list exists nothing is appended and the report says so.
* Without a template it writes the standalone file that contains only the
  documented sections (GlobalVariables, ProjectConfigurations).  Whether the
  exporter merges a partial file with its defaults must be tested in
  MicroStation (docs/MicroStation_verifiering.md, V-07).

Usage:
    python export/build_schema_mapping.py                      # standalone file
    python export/build_schema_mapping.py --template output/env/00_SchemaMapping.json
"""

from __future__ import annotations

import argparse
import copy
import json
import os
import re
import sys
from typing import Any, Dict, List, Optional, Tuple

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from common.config import load_config, repo_path  # noqa: E402

GLOBAL_VARIABLES = {
    # export property values that are empty strings/zero (all our Item Type values are filled)
    "ProcessEmptyProperties": "false",
    # keep the switch assembly as its own element with its own properties
    "JoinAssemblies": "false",
    "ConstructionElements": "false",
    # DGN named groups are DGN-internal; IfcBuiltSystem is produced from the Item Types
    "ProcessGroupingElements": "false",
}

# IFC classes that DGN elements are classified as (Bentley 'IFC Classification' Item Type).
# IfcProject/IfcSite are created by the exporter from ProjectConfigurations and
# IfcBuiltSystem is a group without geometry, so they are not element classes.
def ifc_classes(cfg) -> List[str]:
    return list(cfg.mapping["bentley_ifc_classification"]["apply_to_entities"])

HEADER = """/*
  Branschutmaningen 2026 - Schema Mapping File for MicroStation's iTwin IFC exporter (IFC 4.3).
  Generated by export/build_schema_mapping.py from config/model_config.yaml.
  %s
*/
"""


def strip_json_comments(text: str) -> str:
    out, i, n, in_str = [], 0, len(text), False
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 2
                continue
            if c == '"':
                in_str = False
            i += 1
            continue
        if c == '"':
            in_str = True
            out.append(c)
            i += 1
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            i = n if j < 0 else j + 2
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        else:
            out.append(c)
            i += 1
    return "".join(out)


def loads_jsonc(text: str) -> Any:
    return json.loads(re.sub(r",(\s*[}\]])", r"\1", strip_json_comments(text)))


def project_configurations(cfg) -> Dict[str, Any]:
    m = cfg.model
    return {
        "ProjectName": m["project"]["name"],
        "SiteName": m["site"]["name"],
        "Authorization": "",
        "Author": {"AuthorFirstName": "Branschutmaningen", "AuthorLastName": "2026", "AuthorRole": "ENGINEER",
                   "AuthorEmail": "", "AuthorPhoneNo": ""},
        "Organization": {"OrganizationName": "Branschutmaningen 2026", "OrgAddressCountry": "Sverige",
                         "OrgAddressPostCode": "", "OrgAddressCity": "Stockholm", "OrgAddressState": "",
                         "OrgAddressLine1": "", "OrgAddressLine2": ""},
    }


def _find_class_lists(node: Any, path: str = "") -> List[Tuple[str, list]]:
    """All lists that contain objects with a 'Class' key."""
    found = []
    if isinstance(node, dict):
        for k, v in node.items():
            found.extend(_find_class_lists(v, path + "/" + k))
    elif isinstance(node, list):
        if any(isinstance(x, dict) and "Class" in x for x in node):
            found.append((path, node))
        for i, v in enumerate(node):
            found.extend(_find_class_lists(v, "%s[%d]" % (path, i)))
    return found


def merge(template: Optional[Dict[str, Any]], cfg) -> Tuple[Dict[str, Any], Dict[str, Any]]:
    report: Dict[str, Any] = {"template": template is not None, "class_entries_added": [], "notes": []}
    doc = copy.deepcopy(template) if template is not None else {}
    gv = doc.setdefault("GlobalVariables", {})
    for k, v in GLOBAL_VARIABLES.items():
        gv[k] = v
    doc["ProjectConfigurations"] = project_configurations(cfg)
    if template is None:
        report["notes"].append("standalone: only documented sections written (no class list)")
        return doc, report
    lists = _find_class_lists(doc)
    dyn = [(p, l) for p, l in lists if any(isinstance(x, dict) and isinstance(x.get("Class"), list)
                                              and x["Class"] and x["Class"][0] == "IFCDynamic" for x in l)]
    if not dyn:
        report["notes"].append("template has no IFCDynamic class list - nothing appended; check the template")
        return doc, report
    path, target = dyn[0]
    report["class_list_path"] = path
    existing = {tuple(x["Class"]) for x in target if isinstance(x, dict) and isinstance(x.get("Class"), list)}
    existing_ifc = {c[-1] for c in existing}
    sample = next(x for x in target if isinstance(x, dict) and isinstance(x.get("Class"), list)
                  and x["Class"][0] == "IFCDynamic")
    for ifc in ifc_classes(cfg):
        if ifc in existing_ifc:
            continue
        entry = copy.deepcopy(sample)
        entry["Class"] = ["IFCDynamic", ifc, ifc]
        target.append(entry)
        report["class_entries_added"].append(ifc)
    return doc, report


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--template", help="default SchemaMapping file of the installed exporter")
    ap.add_argument("--out", default=None)
    args = ap.parse_args(argv)
    cfg = load_config()
    template = None
    if args.template:
        with open(args.template, encoding="utf-8") as fh:
            template = loads_jsonc(fh.read())
    doc, report = merge(template, cfg)
    note = ("Merged with template %s (template content unchanged except GlobalVariables, "
            "ProjectConfigurations and appended IFCDynamic class entries)." % os.path.basename(args.template)
            if template is not None else
            "STANDALONE VERSION: contains only the sections whose syntax is publicly documented by Bentley "
            "(GlobalVariables, ProjectConfigurations). Regenerate with --template <installed default mapping> "
            "before the production export, see export/README.md.")
    out = args.out or cfg.file("schema_mapping")
    text = HEADER % note + json.dumps(doc, ensure_ascii=False, indent=2) + "\n"
    loads_jsonc(text)  # self check
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(text)
    with open(repo_path(os.path.join("export", "schema_mapping_build_report.json")), "w", encoding="utf-8") as fh:
        json.dump(report, fh, ensure_ascii=False, indent=1)
    print("SchemaMapping:", out)
    print(json.dumps(report, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
